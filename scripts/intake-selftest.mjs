import assert from 'node:assert/strict';
import { intakeDecision, intakeFingerprint, canEnterLedger, planRecognizedInvoice } from '../src/lib/invoice-intake.js';
import { buildReceiptPayment, transferReceipt } from '../src/lib/receipt-transfer.js';

const buyers = ['测试公司'];
const valid = { name:'fixture.pdf', status:'done', fields:{number:'26440000000000000001',buyer:'测试公司',seller:'测试厂家',date:'2026-11-11',type:'普通发票',docType:'增值税发票',amount:100,tax:6,total:106} };
const copy = () => structuredClone(valid);
assert.equal(intakeDecision(valid,buyers).state,'ready');
assert.equal(intakeDecision(valid,[]).state,'review');
const bad = copy(); bad.fields.buyer='其他公司';
assert.equal(canEnterLedger(bad,buyers),false);
assert.throws(()=>planRecognizedInvoice({},bad,buyers));
bad.expenseTag='交通'; bad.expenseTagSet=true;
assert.equal(canEnterLedger(bad,buyers),false,'费用标签不绕过购买方校验');
bad.fields.buyer=' 测试 公司 ';
assert.equal(intakeDecision(bad,buyers).state,'ready','修正购买方后可保存');
bad.otherReceiptConfirmed=true;
assert.equal(intakeDecision(bad,buyers).state,'receipt');
assert.throws(()=>planRecognizedInvoice({},bad,buyers));
for(const type of ['医疗票据','货物运输凭证','收款凭证','其他票据']) {
 const inv=copy(); inv.fields.docType=type;
 assert.equal(intakeDecision(inv,buyers).state,'receipt',type+'只能走付款凭证');
 assert.equal(canEnterLedger(inv,buyers),false);
}
const incomplete=copy();incomplete.fields.total='';
assert.equal(intakeDecision(incomplete,buyers).state,'review');
const plan=planRecognizedInvoice({},valid,buyers);
const entry=plan.ledger[plan.key];
assert.equal(entry.printed,false);assert.equal(entry.verified,false);assert.equal(entry.reimbursement,'未核对');
const saved=copy();saved.savedFingerprint=intakeFingerprint(saved);
assert.equal(intakeDecision(saved,buyers,plan.ledger).state,'saved');
assert.equal(intakeDecision(saved,buyers,{}).state,'ready','台账移入回收站后不错误显示已保存');
const conflict={...entry,total:999};
assert.throws(()=>planRecognizedInvoice({[plan.key]:conflict},valid,buyers));
assert.equal(conflict.total,999);
const official={...entry,verified:true,printed:true,reviewedAt:'old',reimbursement:'已报销',validTax:4,payer:'垫付人',tags:'保留'};
const merged=planRecognizedInvoice({[plan.key]:official},valid,buyers).ledger[plan.key];
assert.equal(merged.validTax,4);assert.equal(merged.payer,'垫付人');assert.equal(merged.reimbursement,'已报销');
const trip=copy();trip.fields.docType='医疗票据';trip.fields.buyer='';trip.blob=new Blob(['fixture']);
const payment=buildReceiptPayment(trip,'hash');
assert.equal(payment.evidenceConfirmed,false);assert.equal(payment.sourceKind,'receipt');assert.ok(payment.tags.includes('其他票据'));assert.equal(payment.receiptFields.buyer,'');
let rows=[], attachmentWrites=0;
const ports={getRows:()=>rows,saveRows:value=>{rows=value;},saveAttachment:async()=>{attachmentWrites++;},hashFile:async()=> 'hash'};
const transferred=await transferReceipt(trip,ports);
assert.equal(transferred.existing,false);assert.equal(rows.length,1);
assert.equal((await transferReceipt(trip,ports)).existing,true);assert.equal(rows.length,1);assert.equal(attachmentWrites,1);
await assert.rejects(transferReceipt(trip,{...ports,getRows:()=>[],saveAttachment:async()=>{throw Error('附件失败');}}));
await assert.rejects(transferReceipt(trip,{...ports,getRows:()=>[],saveRows:()=>{throw Error('记录失败');}}));
assert.equal(trip.paymentId,undefined,'失败不改变本批原件状态');
console.log('购买方入账拦截、二次确认、独立费用分流、原件失败保护和去重测试通过');
