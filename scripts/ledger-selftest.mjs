import assert from "node:assert/strict";
import * as XLSX from "xlsx";
import { buildHistoryReportBytes, deductionStatus, historyStatus, importInputInvoiceRows, importInputInvoiceWorkbookBytes, missingReimbursementFields, redInvoiceStatus } from "../src/lib/invoice-ledger.js";
import { planLedgerMatches, syncLedgerMatches } from "../src/lib/ledger-matching.js";

const header = ["数电发票号码", "开票日期", "勾选状态", "金额", "税额", "有效抵扣税额", "票种", "票种标签", "勾选时间", "发票状态", "是否正数发票"];
const rows = [header, ["26442000000000000001", "2026-03-19", "已勾选", "100", "13", "10", "专票", "增值税专用发票", "2026-05-18 11:40:39", "正常", "是"]];
let { ledger } = importInputInvoiceRows({}, rows, { importedAt: "2026-10-29" });
let entry = ledger["26442000000000000001"];
assert.equal(entry.validTax, 10);
assert.equal(entry.typeLabel, "增值税专用发票");
assert.equal(entry.selectionTime, "2026-05-18 11:40:39");
assert.equal(entry.verified, true);
assert.equal(deductionStatus({ selectionTime: "2026-05-18 11:40:39" }), "已抵税");
assert.equal(deductionStatus({ officialSelection: "已勾选" }), "已抵税");
assert.equal(deductionStatus({ officialSelection: "否", selectionTime: "2026-05-18" }), "已抵税");
assert.equal(deductionStatus({ officialSelection: "否", selectionTime: "--" }), "未勾选");
assert.equal(deductionStatus({}), "未知");
assert.deepEqual(missingReimbursementFields({ reimburser: "张三", project: "工地甲" }), ["用途"]);
assert.deepEqual(missingReimbursementFields({ reimburser: "张三", project: "工地甲", purpose: "材料" }), []);
const timeOnly = importInputInvoiceRows({}, [["发票号码", "开票日期", "勾选时间"], ["26442000000000000002", "2026-03-19", "2026-04-01"]]).ledger;
assert.equal(historyStatus(timeOnly, { fields: { number: "26442000000000000002" } }).verified, true);
ledger = importInputInvoiceRows(ledger, [["发票号码", "开票日期", "金额", "价税合计"], [entry.number, "2026-03-19", "100", "113"]]).ledger;
entry = ledger[entry.number];
assert.equal(entry.validTax, 10);
assert.equal(entry.typeLabel, "增值税专用发票");
assert.equal(entry.officialSelection, "已勾选");
assert.equal(entry.total, 113);
assert.equal(redInvoiceStatus({ redBlue: "否" }), "红字发票");
assert.equal(redInvoiceStatus({ amount: -1 }), "红字发票");
assert.equal(redInvoiceStatus({ invoiceStatus: "部分冲红" }), "部分冲红");
assert.equal(redInvoiceStatus({ invoiceStatus: "全额冲红" }), "已冲红");
assert.equal(redInvoiceStatus({ invoiceStatus: "正常", redBlue: "是" }), "");
const wb = XLSX.read(buildHistoryReportBytes(ledger), { type: "array" });
const exported = XLSX.utils.sheet_to_json(wb.Sheets[wb.SheetNames[0]], { defval: "" });
assert.equal(exported[0]["有效抵扣税额"], 10);
assert.equal(exported[0]["票种标签"], "增值税专用发票");
assert.equal(exported[0]["勾选时间"], "2026-05-18 11:40:39");
assert.equal(exported[0]["抵税状态"], "已抵税");
const recordWithReimbursement = { ...ledger, [entry.number]: { ...entry, reimburser: "张三", project: "工地甲", purpose: "材料", reimbursement: "已报销" } };
const refreshed = importInputInvoiceRows(recordWithReimbursement, rows).ledger[entry.number];
assert.equal(refreshed.reimburser, "张三"); assert.equal(refreshed.project, "工地甲"); assert.equal(refreshed.purpose, "材料");
const exportedReimbursement = XLSX.read(buildHistoryReportBytes(recordWithReimbursement), { type: "array" });
const exportedRow = XLSX.utils.sheet_to_json(exportedReimbursement.Sheets[exportedReimbursement.SheetNames[0]], { defval: "" })[0];
assert.equal(exportedRow["报销人"], "张三"); assert.equal(exportedRow["工地"], "工地甲"); assert.equal(exportedRow["用途"], "材料");
const details = [["数电发票号码", "开票日期", "货物或应税劳务名称", "金额", "税额", "价税合计"], ["26442000000000000001", "2026-03-19", "项目甲", 40, 5, 45], ["26442000000000000001", "2026-03-19", "项目乙", 60, 8, 68]];
const detailOnly = XLSX.utils.book_new();
XLSX.utils.book_append_sheet(detailOnly, XLSX.utils.aoa_to_sheet(details), "信息汇总表");
const summed = importInputInvoiceWorkbookBytes({}, XLSX.write(detailOnly, { type: "array", bookType: "xlsx" }));
assert.equal(summed.imported, 1);
assert.equal(summed.ledger[entry.number].total, 113);
assert.equal(summed.ledger[entry.number].details.length, 2);
const both = XLSX.utils.book_new();
XLSX.utils.book_append_sheet(both, XLSX.utils.aoa_to_sheet(details), "信息汇总表");
XLSX.utils.book_append_sheet(both, XLSX.utils.aoa_to_sheet([["数电发票号码", "开票日期", "金额", "税额", "价税合计"], [entry.number, "2026-03-19", 100, 13, 113]]), "发票基础信息");
const withBase = importInputInvoiceWorkbookBytes({}, XLSX.write(both, { type: "array", bookType: "xlsx" }));
assert.equal(withBase.imported, 1);
assert.equal(withBase.ledger[entry.number].total, 113);
assert.equal(withBase.ledger[entry.number].details.length, 2);
const file = { name: "发票.pdf" };
const good = { status: "done", blob: file, fields: { number: entry.number, date: "2026-03-19", total: 113 } };
assert.equal(planLedgerMatches(ledger, [good]).matches.length, 1);
assert.equal(planLedgerMatches(ledger, [good, good]).needsReview, 1);
assert.equal(planLedgerMatches(ledger, [{ ...good, fields: { ...good.fields, total: 999 } }]).needsReview, 1);
assert.equal(planLedgerMatches(ledger, [{ ...good, fields: { ...good.fields, total: 113.01 } }]).matches.length, 1);
assert.equal(planLedgerMatches(ledger, [{ ...good, fields: { ...good.fields, total: 113.02 } }]).needsReview, 1);
const legacy = { '12345678': { key: '12345678', code: '123456789012' } };
assert.equal(planLedgerMatches(legacy, [{ status: 'done', blob: file, fields: { number: '12345678' } }]).needsReview, 1);
assert.equal(planLedgerMatches(legacy, [{ status: 'done', blob: file, fields: { number: '12345678', code: '123456789012' } }]).matches.length, 1);
assert.equal(historyStatus(legacy, { fields: { number: '12345678' } }).needsReview, true);
assert.equal(historyStatus(ledger, { fields: { number: entry.number, total: 999 } }).needsReview, true);
const existing = await syncLedgerMatches(ledger, [good], async () => false);
assert.equal(existing.existing, 1);
assert.equal(existing.saved, 0);
const fresh = await syncLedgerMatches(ledger, [good], async () => true);
assert.equal(fresh.saved, 1);
console.log("台账字段、合并、红冲标记和导出检查通过。");
