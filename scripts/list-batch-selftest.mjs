import assert from 'node:assert/strict';
import * as XLSX from 'xlsx/xlsx.mjs';
import {parseAssignmentWorkbook,reviewAssignmentImport} from '../src/lib/expense-assignment-import.js';
import {readPaymentBatch} from '../src/lib/payment-records.js';
import {planPaymentAttachments} from '../src/lib/payment-batch-matching.js';
import {resolveEvidenceReference} from '../src/lib/payment-sheet-files.js';
const book=(rows,setup)=>{const wb=XLSX.utils.book_new(),ws=XLSX.utils.aoa_to_sheet(rows);setup?.(ws);XLSX.utils.book_append_sheet(wb,ws,'公司甲');return XLSX.write(wb,{type:'array',bookType:'xlsx'});};
const num='20260000000000000001',date='2026-07-03',seller='示例商户';
const invoice=book([['费用明细'],['发票日期','发票号码','公司名称','金额','使用工地'],[date,num,seller,35,'东区'],[date,'00123456',seller,80,'']],ws=>{ws['!merges']=[XLSX.utils.decode_range('E3:E4')];});
const data=parseAssignmentWorkbook(invoice,'报账.xlsx');
assert.equal(data.invoices[1].project,'东区');assert.equal(data.invoices[1].sourceRow,'4');
const ledger=Object.fromEntries(data.invoices.map(r=>[r.number,{...r,project:'',allocation:'',reimbursement:'已报销'}]));
const run=rows=>reviewAssignmentImport({...data,invoices:rows},ledger,[],{projects:['东区']});
assert.ok(run(data.invoices).every(i=>i.canApply));assert.ok(run([data.invoices[0],{...data.invoices[0],id:'second'}]).every(i=>!i.canApply));
assert.equal(run([{...data.invoices[0],total:35.01}])[0].canApply,false);
const workbook=book([['下单日期','收款名称','金额（元）','附件','报销状态'],[date,seller,35,'查看原件','已报销']],ws=>{ws.D2.l={Target:'付款凭证/a.pdf'};});
const [record]=readPaymentBatch(workbook,'批次/付款表.xlsx').records;
assert.equal(record.total,35);assert.equal(record.originalStatus,'已报销');assert.deepEqual(record.attachmentRefs,['付款凭证/a.pdf']);
const paid={file:{name:'a.pdf'},hash:'abc',paths:['批次/付款凭证/a.pdf'],fields:{kind:'payment',paymentStatus:'success',direction:'expense',date,seller,total:35}};
const plan=(rows,files=[paid],existing=[])=>planPaymentAttachments(rows,files,existing).get(rows[0].id);
assert.equal(plan([record]).choices[0].kind,'付款凭证');
const ocrRow={...record,attachmentRefs:[]};assert.equal(plan([ocrRow]).choices.length,1);
assert.equal(plan([ocrRow,{...ocrRow,id:'another'}]).choices.length,0);
assert.equal(plan([record],[{...paid,fields:{...paid.fields,total:36}}]).choices.length,0);
assert.equal(plan([record],[{...paid,fields:{...paid.fields,direction:'income'}}]).choices.length,0);
assert.equal(plan([record],[paid],[{id:'other',evidenceHash:'abc'}]).choices.length,0);
assert.equal(plan([record],[paid],[{...record,evidenceHash:'abc'}]).choices.length,0);
assert.equal(plan([record],[{...paid,fields:{kind:'order'}}]).choices[0].kind,'订单详情');
assert.deepEqual(resolveEvidenceReference('凭证/a.pdf','批次/单.xlsx',[{paths:['其他批次/凭证/a.pdf']}]),[]);
assert.equal(plan([record],[]).notes.length,1);
console.log('原发票清单、旧式票号、合并工地、精确附件路径、原表报销状态、歧义及重复附件验证通过');
