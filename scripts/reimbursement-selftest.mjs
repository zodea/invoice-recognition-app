import assert from "node:assert/strict";
import * as XLSX from "xlsx";
import { markReimbursedBatch, historyStatus, shouldDefaultExcludeByHistory, buildHistoryReportBytes, updateCurrentReimbursements, setInvoiceExpenseTag } from "../src/lib/invoice-ledger.js";
import { inferExpenseTag } from "../src/lib/invoice-tags.js";
import { confirmedDuplicateInvoices } from "../src/lib/invoice-dedupe.js";

const a = "26442000004900444576", b = "26442000004900444577";
const initial = { [a]: { key: a, number: a, project: "工地" }, [b]: { key: b, number: b, reimbursement: "已报销", reimbursementDate: "2026-01-01" } };
const result = markReimbursedBatch(initial, [a, a, b], "2026-06-12");
assert.equal(result.marked, 1);
assert.equal(result.already, 1);
assert.equal(result.ledger[a].reimbursementDate, "2026-06-12");
assert.equal(result.ledger[b].reimbursementDate, "2026-01-01");
assert.equal(initial[a].reimbursement, undefined);
assert.throws(() => markReimbursedBatch(initial, [a], "2026-02-30"));
const inv = { fields: { number: a } };
assert.equal(historyStatus(result.ledger, inv).entry.reimbursement, "已报销");
assert.equal(shouldDefaultExcludeByHistory(result.ledger, inv), true);
const rows = XLSX.utils.sheet_to_json(XLSX.read(buildHistoryReportBytes(result.ledger), { type: "array" }).Sheets["历史发票台账"], { header: 1 });
assert.equal(rows.find(row => row[0] === a)[rows[0].indexOf("报销日期")], "2026-06-12");
const current = { status: "done", fields: { number: a, category: "汽油", date: "2026-05-01", total: 50 } };
const created = updateCurrentReimbursements({}, [current], "mark", "2026-06-12");
assert.equal(created.ledger[a].expenseTag, "交通");
assert.equal(created.ledger[a].reimbursementDate, "2026-06-12");
const canceled = updateCurrentReimbursements(created.ledger, [current], "cancel");
assert.equal(canceled.ledger[a].reimbursement, "未核对");
assert.equal(canceled.ledger[a].reimbursementDate, "");
assert.equal(canceled.ledger[a].expenseTag, "交通");
assert.equal(updateCurrentReimbursements(created.ledger, [current, current], "cancel").skipped, 2);
assert.equal(updateCurrentReimbursements({ [a]: { key: a, total: 99 } }, [current], "mark", "2026-06-12").skipped, 1);
assert.equal(updateCurrentReimbursements({}, [{ status: "done", fields: { number: "12345678" } }], "mark", "2026-06-12").skipped, 1);
assert.equal(inferExpenseTag({ service: "住宿和餐饮服务" }), "");
assert.equal(inferExpenseTag({ service: "话费" }), "通讯");
const manual = setInvoiceExpenseTag(created.ledger, current, "餐饮");
assert.equal(updateCurrentReimbursements(manual, [current], "cancel").ledger[a].expenseTag, "餐饮");
const complete = { status: "done", fields: { number: a, date: "2026-05-01", seller: "销售方", total: "50", amount: "45", type: "发票" } };
const duplicate = { ...complete, fields: { ...complete.fields } };
const noNumber = { ...complete, fields: { ...complete.fields, number: "" } };
const changedTotal = { ...complete, fields: { ...complete.fields, total: "51" } };
const differentNumber = { ...complete, fields: { ...complete.fields, number: b } };
assert.deepEqual(confirmedDuplicateInvoices([noNumber, complete, duplicate, changedTotal, differentNumber]), [duplicate]);
assert.deepEqual(confirmedDuplicateInvoices([{ ...complete, status: "idle" }, complete]), []);
console.log("批量报销、日期、重复提醒及导出验证通过");
