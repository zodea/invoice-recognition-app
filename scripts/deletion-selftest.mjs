import assert from 'node:assert/strict';
import { moveLedgerToTrash, restoreLedgerFromTrash, persistLedgerTransition, loadLedgerTrash, readLedgerTrashForChange } from '../src/lib/ledger-trash.js';
import { createRenderer } from 'vue';
import { useConfirmation } from '../src/composables/useConfirmation.js';

assert.throws(()=>readLedgerTrashForChange({getItem:()=>'{invalid'}));
assert.throws(()=>readLedgerTrashForChange({getItem:()=>'{"unexpected":true}'}));

let confirm;
const renderer=createRenderer({createComment:()=>({}),insert(){},remove(){},parentNode:()=>null,nextSibling:()=>null});
const app=renderer.createApp({setup(){confirm=useConfirmation();return ()=>null;}});
app.mount({});
const canceled=confirm.requestConfirmation('删除','测试');
assert.equal(await confirm.requestConfirmation('重复','重复'),false);
confirm.answerConfirmation(false);
assert.equal(await canceled,false);
const accepted=confirm.requestConfirmation('删除','测试');
confirm.answerConfirmation(true);
assert.equal(await accepted,true);
const unmounted=confirm.requestConfirmation('删除','测试');
app.unmount();
assert.equal(await unmounted,false,'离开页面取消尚未确认的删除');

const ledger = { a: {key:'a',number:'10000001',total:100,reimbursement:'已报销'}, b: {key:'b',number:'10000002',total:200} };
const deleted = moveLedgerToTrash(ledger, [], ['a','a','missing']);
assert.equal(deleted.changed, 1);
assert.deepEqual(Object.keys(deleted.ledger), ['b']);
assert.equal(ledger.a.total, 100, '原对象不能被修改');
assert.deepEqual(deleted.trash[0].entry, ledger.a, '报销等所有字段完整保留');
const batch = moveLedgerToTrash(ledger, [], ['a','b']);
assert.equal(batch.changed, 2);
assert.deepEqual(batch.ledger, {});
const restored = restoreLedgerFromTrash(deleted.ledger, deleted.trash, [deleted.trash[0].id]);
assert.deepEqual(restored.ledger, ledger);
assert.equal(restored.trash.length, 0);
const conflict = restoreLedgerFromTrash({a:{total:999}}, deleted.trash, [deleted.trash[0].id]);
assert.equal(conflict.conflicts, 1);
assert.equal(conflict.ledger.a.total, 999);
assert.equal(conflict.trash.length, 1);
const twice = moveLedgerToTrash(ledger, deleted.trash, ['a']);
assert.equal(twice.trash.length, 2, '重新导入后再删除不能覆盖旧备份');
assert.notEqual(twice.trash[0].id, twice.trash[1].id);

const memory = new Map();
const storage = { getItem:k=>memory.get(k)??null, setItem:(k,v)=>memory.set(k,v) };
let active = ledger;
persistLedgerTransition(deleted, [], value=>{active=value;}, storage);
assert.equal(active.a, undefined);
assert.equal(loadLedgerTrash(storage)[0].entry.total,100);
persistLedgerTransition(restored, deleted.trash, value=>{active=value;}, storage);
assert.deepEqual(active, ledger);
assert.deepEqual(loadLedgerTrash(storage), []);
assert.throws(()=>persistLedgerTransition(deleted, [], ()=>{throw Error('台账写入失败');}, storage));
assert.equal(active.a.total,100);
assert.equal(loadLedgerTrash(storage)[0].entry.total,100, '写入失败仍保留可恢复副本');
let saved=false;
assert.throws(()=>persistLedgerTransition(deleted, [], ()=>{saved=true;}, {setItem(){throw Error('空间不足');}}));
assert.equal(saved,false, '备份失败必须阻止删除');
let writes=0;
const cleanupFailure=persistLedgerTransition(restored,deleted.trash,v=>{active=v;},{setItem(){if(++writes===2)throw Error('整理失败');}});
assert.deepEqual(active,ledger);
assert.equal(cleanupFailure.trash.length,1);
assert.ok(cleanupFailure.warning);

globalThis.localStorage=storage;
const {directory,saveDirectory,deleteArchive,restoreArchive,suggestAllocation,purgeDeletedArchives}=await import('../src/lib/expense-directory.js');
saveDirectory({...directory,buyers:['公司甲'],projects:['工地甲'],rules:[{seller:'厂家甲',buyer:'公司甲',project:'工地甲'}]});
deleteArchive('buyers','公司甲');
assert.deepEqual(directory.buyers,[]);
assert.equal(directory.deletedArchives.length,1);
assert.equal(suggestAllocation('厂家甲'),null);
assert.equal(ledger.a.total,100);
assert.equal(JSON.parse(storage.getItem('expenseDirectory.v1')).deletedArchives[0].value,'公司甲');
restoreArchive('buyers','公司甲');
assert.deepEqual(directory.buyers,['公司甲']);
assert.equal(suggestAllocation('厂家甲').project,'工地甲');
deleteArchive('projects','工地甲');
assert.equal(suggestAllocation('厂家甲'),null);
restoreArchive('projects','工地甲');
assert.equal(suggestAllocation('厂家甲').project,'工地甲');
const originalSet=storage.setItem;
storage.setItem=()=>{throw Error('存储失败');};
assert.throws(()=>deleteArchive('buyers','公司甲'));
assert.deepEqual(directory.buyers,['公司甲']);
storage.setItem=originalSet;
console.log('单张/批量删除、持久化恢复、同号冲突、保存失败保护、档案恢复与规则停用测试通过');

// 档案永久删除只移除回收站备份；类型相同/名称相同均需精确匹配。
saveDirectory({...directory,buyers:['同名档案'],projects:['同名档案'],deletedArchives:[]});
deleteArchive('buyers','同名档案');
deleteArchive('projects','同名档案');
assert.equal(purgeDeletedArchives([{kind:'buyers',value:'同名档案'}]),1);
assert.equal(directory.deletedArchives.length,1);
assert.equal(directory.deletedArchives[0].kind,'projects');
assert.deepEqual(directory.buyers,[]);
assert.equal(ledger.a.total,100,'永久删除档案不改历史票据');
const prior=JSON.stringify(directory);
storage.setItem=()=>{throw Error('持久化失败');};
assert.throws(()=>purgeDeletedArchives([...directory.deletedArchives]));
assert.equal(JSON.stringify(directory),prior,'写入失败保留档案备份');
storage.setItem=originalSet;
assert.equal(purgeDeletedArchives([...directory.deletedArchives]),1);
assert.equal(directory.deletedArchives.length,0);
assert.equal(purgeDeletedArchives([{kind:'buyers',value:'missing'}]),0);
restoreArchive('projects','同名档案');
assert.deepEqual(directory.projects,[],'永久删除后不能从回收站恢复');
console.log('档案永久删除、类型精确匹配、清空与写入失败保护测试通过');
